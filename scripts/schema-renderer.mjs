const UI_ONLY_TYPES = new Set(['tab', 'accordion', 'message']);

function firstChoice(field) {
    if (field.default_value !== undefined && field.default_value !== '' && field.default_value !== null) {
        return field.default_value;
    }
    const keys = field.choices ? Object.keys(field.choices) : [];
    return keys.length > 0 ? keys[0] : '';
}

function skeletonValue(field) {
    switch (field.type) {
        case 'link': return { title: '', url: '', target: '' };
        case 'gallery': return [];
        case 'true_false': return 0;
        case 'button_group':
        case 'select':
        case 'radio': return firstChoice(field);
        default: return '';
    }
}

/** Fill `data` with every field of `fields` under `prefix` ("" or "cards_0_"). Repeater rows come before the count, matching the real editor output. */
function fillSkeleton(data, fields, prefix) {
    for (const field of fields || []) {
        if (!field.name || UI_ONLY_TYPES.has(field.type)) continue;
        const name = prefix + field.name;
        if (field.type === 'repeater') {
            fillSkeleton(data, field.sub_fields, `${name}_0_`);
            data[name] = 1;
            data[`_${name}`] = field.key;
            continue;
        }
        data[name] = skeletonValue(field);
        data[`_${name}`] = field.key;
    }
}

function blockNameOf(group) {
    for (const ruleGroup of group.location || []) {
        if (!Array.isArray(ruleGroup)) continue;
        for (const rule of ruleGroup) {
            if (rule.param === 'block' && typeof rule.value === 'string') return rule.value;
        }
    }
    return null;
}

export function renderModuleSkeletons(groups) {
    let md = `# Module Skeletons (generated from the live ACF schema)

*This file is autogenerated. DO NOT EDIT.*

Rules:
- Start every block by copying the skeleton of its module and filling the values.
- Every value key has a matching \`_key\` mapping. Keep both. Never add a key that is not in the skeleton, never delete one — leave it empty instead.
- Repeaters: the count field holds the number of rows; duplicate the \`<repeater>_0_<field>\` keys (and their \`_\` mappings) as \`<repeater>_1_<field>\`, \`<repeater>_2_<field>\`, … and set the count accordingly.
- \`button_group\` / \`select\` / \`radio\` values are pre-filled with the default; use only the choices listed in acf-schemas.md.
- Output each block as ONE line, exactly as shown.

`;
    for (const group of groups || []) {
        const blockName = blockNameOf(group);
        if (!blockName || !(group.fields || []).length) continue;
        const data = {};
        fillSkeleton(data, group.fields, '');
        const block = { name: blockName, data, mode: 'edit' };
        md += `### ${blockName}\n\`\`\`html\n<!-- wp:${blockName} ${JSON.stringify(block)} /-->\n\`\`\`\n\n`;
    }
    return md;
}
