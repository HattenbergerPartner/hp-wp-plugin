/**
 * schema-renderer.mjs
 *
 * Pure renderers: JSON in, markdown string out. No I/O, no network.
 *
 * These produce the exact format that references/acf-schemas.md and
 * references/color-system.md have always used, because schema-loader.mjs
 * parses that format. Both the maintainer sync (sync-acf-context.js) and the
 * runtime fetcher (wp-schema-fetcher.mjs) import from here, so the two paths
 * can never diverge.
 */

export const FALLBACK_COLORS = {
    background_colors: [
        { label: 'primary', color: '#3B5998', type: 'basic' },
        { label: 'primary-green', color: '#A8D85B', type: 'basic' },
        { label: 'primary-dark', color: '#1A2744', type: 'basic' },
        { label: 'light-yellow', color: '#F5F0C8', type: 'basic' },
    ],
    text_colors: [
        { label: 'primary', color: '#3B5998' },
        { label: 'white', color: '#FFFFFF' },
    ],
    default_background_color: '#FFFFFF',
    default_text_color: '#1A1A1A',
};

function parseFields(fields, depth = 0) {
    let result = '';
    const indent = '  '.repeat(depth);

    if (!Array.isArray(fields)) return result;

    for (const field of fields) {
        result += `${indent}- **${field.name}** (\`${field.type}\`) -> Key: \`${field.key}\``;

        if (field.choices && (field.type === 'button_group' || field.type === 'select' || field.type === 'radio')) {
            const choiceValues = Object.keys(field.choices);
            if (choiceValues.length > 0) {
                result += ` -> Choices: \`${choiceValues.join('` | `')}\``;
            }
        }

        if (field.default_value !== undefined && field.default_value !== '' && field.default_value !== null) {
            result += ` -> Default: \`${field.default_value}\``;
        }

        if (field.type === 'textarea') {
            const mode = field.new_lines === 'br' || field.new_lines === 'wpautop' ? field.new_lines : 'none';
            result += ` -> Line breaks: \`${mode}\``;
        }

        const max = Number.parseInt(field.maxlength, 10);
        if (Number.isInteger(max) && max > 0) {
            result += ` -> Max length: \`${max}\``;
        }

        result += '\n';

        if (field.instructions) {
            result += `${indent}  - Instructions: ${field.instructions}\n`;
        }

        if (field.sub_fields) {
            result += parseFields(field.sub_fields, depth + 1);
        }
    }
    return result;
}

export function renderAcfSchemas(groups) {
    let markdown = `# WordPress Gutenberg Block Schemas (ACF)

*This file is autogenerated. DO NOT EDIT.*
Below are the valid modules and their explicit field keys. You must use these EXACT \`field_xxxx\` identifiers in your JSON payloads.
For \`button_group\` fields, the valid choices are listed after "Choices:". Use ONLY these values.
Textarea fields carry "Line breaks:" — \`none\`: one paragraph, a hard break needs a literal \`\\u003cbr\\u003e\`; \`br\`: \`\\n\` becomes a line break and \`\\n\\n\` a blank line; \`wpautop\`: \`\\n\\n\` becomes a paragraph like wysiwyg.
Fields with "Max length:" must not exceed that many characters.

`;

    for (const group of groups) {
        const title = group.title || 'Unknown Module';
        const location = group.location || [];

        let isBlock = false;
        let blockName = '';

        for (const ruleGroup of location) {
            if (!Array.isArray(ruleGroup)) continue;
            for (const rule of ruleGroup) {
                if (rule.param === 'block') {
                    isBlock = true;
                    blockName = rule.value;
                }
            }
        }

        const fields = group.fields || [];

        if (fields.length > 0) {
            markdown += `## ${title}\n`;
            if (isBlock) {
                markdown += `**Gutenberg Block Name:** \`${blockName}\`\n\n`;
            }
            markdown += `### Available Fields:\n`;
            markdown += parseFields(fields);
            markdown += `\n---\n\n`;
        }
    }

    return markdown;
}

function getBackgroundUse(label) {
    const map = {
        'primary': 'Brand blue — authority sections, key value propositions',
        'primary-green': 'Yellow-green accent — warm highlights, secondary features',
        'primary-dark': 'Dark blue — high-contrast CTAs, Contact sections',
        'light-yellow': 'Soft yellow — gentle highlights, testimonials, warmth',
    };
    return map[label] || 'Custom color';
}

function getTextUseWith(label) {
    const map = {
        'primary': '`bg-default`, `bg-primary-green`, `bg-light-yellow` (accent blue text)',
        'white': '`bg-primary`, `bg-primary-dark` (light text on dark backgrounds)',
    };
    return map[label] || 'Check contrast before using';
}

